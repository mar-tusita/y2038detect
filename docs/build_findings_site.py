#!/usr/bin/env python3
"""build_findings_site.py — convert evaluation findings Markdown to HTML for GitHub Pages.

Converts evaluation/results/{version}/findings/**/*.md (generated by
evaluation/scripts/05_generate_findings.py) into HTML pages under
{out}/evaluation/findings/{version}/, using the shared docs/template.html5
so the pages match the rest of the site's look.

Which versions get published is decided in this order:
  1. VERSION arguments on the command line, if any;
  2. otherwise the list in docs/findings_versions.txt (one version per line,
     '#' starts a comment line; the order given is the order on the index page);
  3. otherwise, if that file does not exist, the latest version only.
The Deploy GitHub Pages workflow passes no arguments, so it publishes exactly
what docs/findings_versions.txt lists. Editing that file is how a version is
added to or withdrawn from the public site (each deploy replaces the whole
site, so the list must always be complete).

Usage:
    python docs/build_findings_site.py                          # per findings_versions.txt
    python docs/build_findings_site.py v0.9.1_20260914           # specific version(s)
    python docs/build_findings_site.py v0.9.1_20260914 v0.8.0_20260601
    python docs/build_findings_site.py --out _site               # output dir (default: _site)

Requires pandoc on PATH.
"""

import argparse
import csv
import json
import os
import re
import subprocess
import sys

DOCS_DIR      = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR      = os.path.dirname(DOCS_DIR)
RESULTS_DIR   = os.path.join(ROOT_DIR, 'evaluation', 'results')
TEMPLATE      = os.path.join(DOCS_DIR, 'template.html5')
VERSIONS_FILE = os.path.join(DOCS_DIR, 'findings_versions.txt')

# Rewrite relative links to sibling findings Markdown files ("...L42.md)")
# into links to the HTML pages this script generates ("...L42.html)").
_MD_LINK_RE = re.compile(r'(\]\([^)\s]+?)\.md(\)|#)')

# A finding's '## 確認結果' section writes 判定/コメント as two plain lines
# (05_generate_findings.py's template relies on the 判定 line's trailing
# hard-break spaces to keep them visually separate). Reviewers routinely
# lose those trailing spaces when they type their verdict over the line,
# so GFM/CommonMark then treats the two lines as one soft-wrapped paragraph
# and renders them joined by a space. Fixing the source files would mean
# changing the authoring format reviewers already use; this instead
# inserts a real blank line between them only in the published HTML, which
# always separates them into distinct paragraphs regardless of whether the
# hard-break spaces survived.
_VERDICT_COMMENT_RE = re.compile(r'^(判定:.*)\n(コメント:)', re.MULTILINE)


def _latest_version(results_dir=RESULTS_DIR):
    """Return the most recent results dir name that has a findings/ subdir."""
    if not os.path.isdir(results_dir):
        return None
    entries = sorted(
        e for e in os.listdir(results_dir)
        if os.path.isdir(os.path.join(results_dir, e, 'findings'))
    )
    return entries[-1] if entries else None


def _read_versions_file(path):
    """Return the version names listed in path, skipping blank and '#' lines."""
    versions = []
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith('#'):
                versions.append(line)
    return versions


def _resolve_versions(cli_versions, versions_file=VERSIONS_FILE, results_dir=RESULTS_DIR):
    """Decide which versions to publish (see the module docstring for the order).

    Raises ValueError with a user-facing message if nothing can be chosen.
    """
    if cli_versions:
        return list(cli_versions)

    if os.path.isfile(versions_file):
        versions = _read_versions_file(versions_file)
        if not versions:
            # An existing-but-empty list most likely means everything was
            # commented out by mistake; falling back to "latest" would
            # publish something nobody asked for.
            raise ValueError(f'{versions_file} lists no versions.')
        return versions

    latest = _latest_version(results_dir)
    if not latest:
        raise ValueError('no results with findings/ found under evaluation/results/.')
    return [latest]


def _missing_versions(versions, results_dir=RESULTS_DIR):
    """Return the versions that have no findings/ directory."""
    return [v for v in versions
            if not os.path.isdir(os.path.join(results_dir, v, 'findings'))]


def _rewrite_md_links(text):
    return _MD_LINK_RE.sub(lambda m: m.group(1) + '.html' + m.group(2), text)


def _add_verdict_comment_break(text):
    return _VERDICT_COMMENT_RE.sub(
        lambda m: m.group(1).rstrip() + '\n\n' + m.group(2), text)


def _title_from_markdown(text, fallback):
    for line in text.splitlines():
        if line.startswith('# '):
            return line[2:].strip()
    return fallback


def _css_href(html_path, out_dir):
    """Relative path back to {out_dir}/style.css from html_path's location."""
    rel_dir = os.path.dirname(os.path.relpath(html_path, out_dir))
    if not rel_dir or rel_dir == '.':
        return 'style.css'
    depth = rel_dir.count(os.sep) + 1
    return '../' * depth + 'style.css'


def _convert_markdown(text, html_path, title, out_dir):
    os.makedirs(os.path.dirname(html_path), exist_ok=True)
    subprocess.run(
        ['pandoc', '-', '--from', 'gfm', '--to', 'html5',
         '--template', TEMPLATE, '--highlight-style=pygments',
         '-V', 'lang_ja=1',
         '-V', 'no_lang_switch=1',
         '-V', f'css_href={_css_href(html_path, out_dir)}',
         '--metadata', f'title={title}',
         '-o', html_path],
        input=text, text=True, encoding='utf-8', check=True,
    )


# Individual finding pages don't repeat the true-positive/false-positive/
# unclear/wontfix definitions -- they point back to the one copy at the
# top of index.md (see evaluation/scripts/06_aggregate_review.py's
# _CRITERIA_MD), so there is a single place to update the wording and no
# per-file regeneration is needed when it changes.
_CRITERIA_NOTE = (
    '*判定（true-positive / false-positive / unclear / wontfix）の基準は '
    '[一覧ページの「判定基準」](../index.html#判定基準)を参照してください。*'
)


def _load_repo_rows(version, results_dir=RESULTS_DIR):
    """Return repos.json rows for version joined with summary.csv's
    c_files/c_lines (how much of each repo y2038detect actually scanned --
    repos.json's own size_kb is GitHub's compressed-git-object size, not
    useful for that). Returns None if repos.json is missing (older,
    un-backfilled results -- see CLAUDE.md's 04_analyze.py notes).

    A repo present in repos.json can be absent from summary.csv if
    02_scan.py's ScanFailed path skipped writing its record; such rows get
    c_files=c_lines=None rather than 0, so they don't silently count as
    "scanned 0 lines" in the totals.
    """
    repos_json = os.path.join(results_dir, version, 'repos.json')
    if not os.path.isfile(repos_json):
        return None

    with open(repos_json, encoding='utf-8') as f:
        repos = json.load(f)

    counts = {}
    summary_csv = os.path.join(results_dir, version, 'summary.csv')
    if os.path.isfile(summary_csv):
        with open(summary_csv, encoding='utf-8', newline='') as f:
            for row in csv.DictReader(f):
                counts[row['repo']] = (int(row['c_files']), int(row['c_lines']))

    rows = []
    for r in repos:
        repo = r.get('repo', '')
        c_files, c_lines = counts.get(repo, (None, None))
        rows.append({
            'repo': repo, 'domain': r.get('domain', '-'),
            'collected_at': r.get('collected_at', '-'),
            'c_files': c_files, 'c_lines': c_lines,
        })
    return sorted(rows, key=lambda r: r['repo'])


def _repos_markdown(version, results_dir=RESULTS_DIR):
    """Build evaluation/findings/{version}/repos.html's Markdown: which
    repos were scanned, their domain and collection date, and how much
    y2038detect actually processed per repo (.c files/lines) and in total.
    Returns None (no page) if repos.json isn't available for version.
    """
    rows = _load_repo_rows(version, results_dir)
    if rows is None:
        return None

    total_files = sum(r['c_files'] for r in rows if r['c_files'] is not None)
    total_lines = sum(r['c_lines'] for r in rows if r['c_lines'] is not None)

    lines = [
        f'[← {version} 検出結果一覧](index.html)',
        '',
        f'# {version} 対象リポジトリ一覧',
        '',
        f'y2038detect のスキャン対象とした {len(rows)} 件のリポジトリです。'
        '「.cファイル数」「行数」は、y2038detect が実際にスキャンした `.c` ファイルの'
        '数・行数です（GitHub 上のリポジトリサイズではありません）。',
        '',
        '| # | リポジトリ | ドメイン | .cファイル数 | 行数 | 収集日 |',
        '|---|---|---|---|---|---|',
    ]
    for i, r in enumerate(rows, start=1):
        url = f'https://github.com/{r["repo"]}'
        c_files = f'{r["c_files"]:,}' if r['c_files'] is not None else '—'
        c_lines = f'{r["c_lines"]:,}' if r['c_lines'] is not None else '—'
        lines.append(
            f'| {i} | [{r["repo"]}]({url}) | {r["domain"]} | '
            f'{c_files} | {c_lines} | {r["collected_at"]} |')
    lines.append(f'| | **合計** | | **{total_files:,}** | **{total_lines:,}** | |')
    lines.append('')
    return '\n'.join(lines)


def _index_header():
    return '[← 評価結果一覧](../index.html)\n\n'


# The "対象" line of the 解析条件 section that 06_aggregate_review.py writes
# ("- 対象: 50 リポジトリ、26,980 ファイル、..."). The repository count is
# what repos.html lists, so that is where the link goes. A test builds a
# real section with 06's _conditions_md() to keep this pattern in sync.
_TARGET_LINE_RE = re.compile(r'^(- 対象: )(\d+ リポジトリ)', re.MULTILINE)


def _index_markdown(text, has_repos_page):
    """The version's index.md prepared for HTML: back-link plus the link to
    repos.html (which only exists in the built site, so it is added here
    rather than written into findings/index.md, where it would be dead on
    GitHub).

    The link goes on the 解析条件 "対象" line. An index without that section
    (results generated before it existed) keeps a separate link under the
    back-link instead.
    """
    header = _index_header()
    if has_repos_page:
        text, linked = _TARGET_LINE_RE.subn(r'\1[\2](repos.html)', text, count=1)
        if not linked:
            header += '[対象リポジトリ一覧](repos.html)\n\n'
    return header + text


def _finding_header(version):
    return f'[← {version} 一覧に戻る](../index.html)\n\n{_CRITERIA_NOTE}\n\n'


def _convert_version(version, out_dir):
    findings_dir = os.path.join(RESULTS_DIR, version, 'findings')
    if not os.path.isdir(findings_dir):
        print(f'Error: {findings_dir} not found.', file=sys.stderr)
        return 0

    out_version_dir = os.path.join(out_dir, 'evaluation', 'findings', version)
    count = 0

    repos_md = _repos_markdown(version)
    if repos_md is not None:
        repos_html_path = os.path.join(out_version_dir, 'repos.html')
        title = _title_from_markdown(repos_md, f'{version} 対象リポジトリ一覧')
        _convert_markdown(repos_md, repos_html_path, title, out_dir)
        count += 1

    for root, _dirs, files in os.walk(findings_dir):
        for fname in sorted(files):
            if not fname.endswith('.md'):
                continue
            md_path = os.path.join(root, fname)
            with open(md_path, encoding='utf-8') as f:
                text = _add_verdict_comment_break(_rewrite_md_links(f.read()))

            rel = os.path.relpath(md_path, findings_dir)
            html_rel = os.path.splitext(rel)[0] + '.html'
            html_path = os.path.join(out_version_dir, html_rel)

            if fname == 'index.md':
                text = _index_markdown(text, has_repos_page=repos_md is not None)
                default_title = f'{version} 評価結果一覧'
            else:
                text = _finding_header(version) + text
                default_title = fname

            title = _title_from_markdown(text, default_title)
            _convert_markdown(text, html_path, title, out_dir)
            count += 1
    return count


def _write_top_index(out_dir, versions):
    lines = [
        '[← y2038detect トップ](../../)',
        '',
        '# y2038detect 評価結果',
        '',
        'バージョンごとの評価結果を公開しています（検出箇所は1件ごとに1ページにまとめています）。',
        '',
    ]
    for v in versions:
        lines.append(f'- [{v}]({v}/index.html)')
    text = '\n'.join(lines) + '\n'

    out_path = os.path.join(out_dir, 'evaluation', 'findings', 'index.html')
    _convert_markdown(text, out_path, 'y2038detect 評価結果', out_dir)


def main():
    parser = argparse.ArgumentParser(
        description='Convert evaluation findings Markdown to HTML for GitHub Pages.')
    parser.add_argument('versions', nargs='*', metavar='VERSION',
                        help='results version dir name(s) '
                             '(default: the list in docs/findings_versions.txt, '
                             'or the latest version if that file does not exist)')
    parser.add_argument('--out', default='_site', metavar='DIR',
                        help='output site directory (default: _site)')
    args = parser.parse_args()

    try:
        versions = _resolve_versions(args.versions)
    except ValueError as e:
        print(f'Error: {e}', file=sys.stderr)
        sys.exit(1)

    missing = _missing_versions(versions)
    if missing:
        for v in missing:
            print(f'Error: evaluation/results/{v}/findings not found.', file=sys.stderr)
        sys.exit(1)

    total = 0
    for version in versions:
        n = _convert_version(version, args.out)
        print(f'{version}: {n} pages')
        total += n

    _write_top_index(args.out, versions)
    print(f'Total: {total} pages under '
          f'{os.path.join(args.out, "evaluation", "findings")}')


if __name__ == '__main__':
    main()
